"""Render the dataset registry and dictionaries as docs/datasets.md.

The registry already knows every dataset's prefix, FTP directory, cadence,
partitioning and coverage. Writing that into hand-maintained per-dataset pages
means the same fact lives in two places and the docs drift.

Run with ``--check`` to fail when the committed file is stale — the same
pattern as ``ruff format --check``. The file is committed, so the docs build
stays a plain ``mkdocs build`` with no extra plugin.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from omnisus.sources.datasus_ftp.datasets import REGISTRY
from omnisus.transforms.dictionaries import load_dicionario

OUT = Path(__file__).resolve().parent.parent / "docs" / "datasets.md"

HEADER = """<!-- Generated by scripts/gen_datasets_doc.py. Do not edit by hand. -->

# Bases e argumentos

Cada linha é uma base do registro (`src/omnisus/sources/datasus_ftp/datasets.py`) e diz
o que passar para `sus.load` e `sus.available`. A página é gerada do registro e dos
dicionários da versão que você está lendo; `help(sus.load)` mostra o mesmo na versão
instalada.

```python
import omnisus as sus

sus.load("sim_obitos", years=[2023], ufs=["RR"])        # base por UF
sus.load("sinan_chagas", years=[2023])                  # base nacional: sem ufs
sus.load("sih_aih_reduzida", years=[2024], ufs=["RR"], months=[1, 2])
```

- **`years`**: anos dentro da cobertura. "em diante" quer dizer que não há ano final
  declarado, não que todo ano exista; `sus.available(base)` lista o que o servidor
  publica hoje.
- **`ufs`**: siglas das UFs (`sus.ALL_UFS` para todas). Bases nacionais aceitam só `None`.
- **`months`**: meses 1 a 12 das bases mensais; `None` quer dizer todos.
- **Colunas com rótulo**: as que `sus.label` rotula, pelo mapa `x-decode` do dicionário
  (o link abre o dicionário).
- **Diretório**: onde a base fica em `ftp://ftp.datasus.gov.br/dissemin/publicos/`.

"""

FOOTER = """
A cobertura é a janela declarada no registro. Um workflow semanal
(`tests/integration/test_registry_probe.py`) confere diretórios, prefixos, primeiros
arquivos e publicações recentes contra o servidor, fora do CI de pull request.

Esta tabela cobre as bases do FTP do DATASUS. População do IBGE, SIGTAP e nomes do
CNES têm funções próprias: [IBGE](sources/ibge_populacao.md),
[vocabulários e SIGTAP](sources/vocabularios.md) e
[nomes do CNES](sources/cnes_estabelecimentos.md#establishment-names).
"""

FTP_ROOT = "/dissemin/publicos/"
DICIONARIOS = "https://github.com/raphaelfh/omnisus/blob/main/src/omnisus/data/dicionarios"


def render() -> str:
    rows = [
        "| Base | O que é | `years` | `ufs` | `months` | Colunas com rótulo | Diretório |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(REGISTRY):
        d = REGISTRY[name]
        dictionary = load_dicionario(name)
        first, last = d.coverage
        years = f"{first[0]} em diante" if last is None else f"{first[0]} a {last[0]}"
        ufs = "`None`" if d.geography == "national" else "`['RR', ...]`"
        months = "1 a 12" if d.cadence == "monthly" else "—"
        decoded = sum(1 for field in dictionary.fields if field.get("x-decode"))
        rows.append(
            f"| `{d.name}` | {dictionary.title} | {years} | {ufs} | {months} | "
            f"[{decoded}]({DICIONARIOS}/{name}.yaml) | `{d.ftp_dir.removeprefix(FTP_ROOT)}` |"
        )
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file differs from what the registry renders",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(
                f"{OUT} is stale. Run: uv run python scripts/gen_datasets_doc.py", file=sys.stderr
            )
            return 1
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT} ({len(REGISTRY)} datasets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
