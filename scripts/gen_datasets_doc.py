"""Render ``sus.describe_datasets()`` as docs/datasets.md, one section per system.

The table already knows every dataset's system, coverage, publication, directories,
labelled columns and validated scopes; ``sus.describe_dataset`` names the harmonised
categories each dictionary defines. Writing that into hand-maintained pages means the
same fact lives in two places and the docs drift. Each system's section links the
profiles in docs/sources/ whose title names a dataset of the system in backticks.

The dictionary links point at the release tag of the installed version, so the
release PR regenerates the page (RELEASE.md). Run with ``--check`` to fail when the
committed file is stale, the same pattern as ``ruff format --check``. The file is
committed, so the docs build stays a plain ``mkdocs build`` with no extra plugin.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import omnisus as sus

DOCS = Path(__file__).resolve().parent.parent / "docs"
OUT = DOCS / "datasets.md"
FTP_ROOT = "/dissemin/publicos/"
CATEGORIES = {"age": "idade", "sex": "sexo", "dates": "datas"}
"""``x-analytics`` rules, in the order ``analytical_projection`` adds them."""

HEADER = """<!-- Generated by scripts/gen_datasets_doc.py. Do not edit by hand. -->

# Bases e argumentos

Cada linha é uma base do FTP do DATASUS que o omnisus importa: o que é, como é
publicada, desde quando e quantas colunas têm rótulo. O servidor publica outras, que o
pacote não importa. A página é gerada de `sus.describe_datasets()` na versão
{version}; a mesma chamada devolve a tabela da versão instalada. O notebook
[bases.py](https://github.com/raphaelfh/omnisus/blob/main/notebooks/bases.py)
([molab](https://molab.marimo.io/github/raphaelfh/omnisus/blob/main/notebooks/bases.py))
mostra essa tabela e leva qualquer base até a citação.

```python
import omnisus as sus

sus.describe_datasets()                                 # esta página, como tabela
sus.load("sim_obitos", years=[2023], ufs=["RR"])        # por UF, anual
sus.load("sinan_chagas", years=[2023])                  # Brasil, anual: sem ufs
sus.load("sih_aih_reduzida", years=[2024], ufs=["RR"], months=[1, 2])  # por UF, mensal
```

## Como ler

- **Publicação** diz o que passar para `sus.load`. "por UF" pede `ufs` (siglas;
  `sus.ALL_UFS` para todas; em `sus.available` é um filtro opcional); "Brasil" é um
  arquivo nacional, que aceita só `ufs=None`. "mensal" aceita `months` de 1 a 12
  (`None` quer dizer todos); "anual" não tem mês.
- **Cobertura** é a janela declarada no registro, com o mês nas bases mensais: um ano
  ou mês de `sus.load` fora dela é pulado (`outside_coverage`) sem consulta ao
  servidor. Ela não é o que o servidor publica hoje: "em diante" quer dizer que não há
  fim declarado, não que todo período exista, e `sus.available(base)` lista o que
  existe. "+ preliminar" quer dizer que o DATASUS publica também arquivos preliminares,
  num diretório à parte ([Onde fica no servidor](#onde-fica-no-servidor)). `sus.load`
  lê os dois: cada linha diz `final` ou `prelim` em `_source_release`, e
  `sus.available_releases(base)` mostra qual vale para cada escopo.
- **Colunas com rótulo** são as que `sus.label` rotula, pelo mapa `x-decode` do
  dicionário; o link abre o dicionário desta versão.
- **Categorias harmonizadas** diz quais categorias o dicionário da base define (idade
  em `idade_anos_completos`, sexo em `sexo_categoria`, datas em `*_data`) e em quais
  UFs e períodos o arquivo foi auditado (períodos seguidos aparecem como intervalo,
  `2021 a 2024`; `Brasil` nas bases nacionais). `sus.load`
  só as acrescenta quando todos os escopos que devolve estão nesta lista. A validação
  vale para o arquivo: escopo, diretório (final ou preliminar) e SHA-256, que
  `sus.describe_dataset(base)["analytics"]["validated_sources"]` mostra. Se o DATASUS
  republicar o arquivo ou passá-lo do preliminar para o final, as categorias somem até
  uma nova validação. "—" quer dizer nenhum escopo validado; os rótulos valem em
  todos.

Um workflow semanal (`tests/integration/test_registry_probe.py`) confere diretórios,
prefixos, primeiros arquivos e publicações recentes contra o servidor, fora do CI de
pull request.
"""

TABLE = (
    "| Base | O que é | Publicação | Cobertura | Colunas com rótulo | Categorias harmonizadas |\n"
    "| --- | --- | --- | --- | ---: | --- |"
)

SERVER = """
## Onde fica no servidor

Diretórios em `ftp://ftp.datasus.gov.br/dissemin/publicos/`. O prefixo é o começo do
nome de cada arquivo; bases que dividem um diretório se distinguem por ele.

| Base | Prefixo | Diretório | Preliminar |
| --- | --- | --- | --- |"""

OTHERS = """
## Outras fontes

Estas fontes não passam por `sus.load`:

- População municipal do IBGE: `sus.import_ibge_populacao`
  ([IBGE](sources/ibge_populacao.md)).
- UFs, municípios, CID-10, ocupações e países (`aux_*`), que `omnisus init` carrega
  do pacote ([vocabulários](sources/vocabularios.md)).
- Procedimentos do SIGTAP por competência: `sus.import_sigtap`
  ([SIGTAP](sources/vocabularios.md#sigtap-por-competencia)).
- Nomes dos estabelecimentos, pela API pública do CNES (`sus.import_cnes_master`) ou pela base
  completa do CNES no FTP (`import_cnes_master_ftp`)
  ([nomes do CNES](sources/cnes_estabelecimentos.md#establishment-names)).
- Posição de estoque BNAFAR/Hórus, uma página por consulta de `fetch_stock_page`, sem
  gravar no lake ([medicamentos](sources/medicamentos.md#cliente-de-estoque-bnafarhorus)).
"""


def _publication(row: dict) -> str:
    where = "Brasil" if row["geography"] == "national" else "por UF"
    return f"{where}, {'mensal' if row['cadence'] == 'monthly' else 'anual'}"


def _coverage(row: dict) -> str:
    start, end = row["coverage_start"], row["coverage_end"]
    window = f"{start} em diante" if end is None else f"{start} a {end}"
    return window + (" + preliminar" if row["prelim_dir"] else "")


def _labelled(row: dict) -> str:
    url = (
        f"https://github.com/raphaelfh/omnisus/blob/v{sus.__version__}"
        f"/src/omnisus/data/dicionarios/{row['name']}.yaml"
    )
    return f"[{row['labelled_fields']}]({url})"


def _seguinte(periodo: tuple[int, int | None]) -> tuple[int, int | None]:
    ano, mes = periodo
    if mes is None:
        return ano + 1, None
    return (ano + 1, 1) if mes == 12 else (ano, mes + 1)


def _periodo(periodo: tuple[int, int | None]) -> str:
    ano, mes = periodo
    return str(ano) if mes is None else f"{ano}-{mes:02d}"


def _intervalos(periodos: set[tuple[int, int | None]]) -> str:
    """``2021 a 2024``; ``2024-01 a 2024-05, 2025-01 a 2025-02``: consecutive periods joined."""
    intervalos: list[list[tuple[int, int | None]]] = []
    for periodo in sorted(periodos, key=lambda p: (p[0], p[1] or 0)):
        if intervalos and _seguinte(intervalos[-1][1]) == periodo:
            intervalos[-1][1] = periodo
        else:
            intervalos.append([periodo, periodo])
    return ", ".join(
        _periodo(a) if a == b else f"{_periodo(a)} a {_periodo(b)}" for a, b in intervalos
    )


def _escopos(sources: list[dict]) -> str:
    """The validated scopes, UFs with the same periods together.

    ``RR, 2021 a 2024; SP, 2024``; ``27 UFs, 2020 a 2024``; ``Brasil, 2023``.
    """
    por_uf: dict[str | None, set] = defaultdict(set)
    for source in sources:
        por_uf[source.get("uf")].add((source["ano"], source.get("mes")))
    por_intervalo: dict[str, list] = defaultdict(list)
    for uf, periodos in por_uf.items():
        por_intervalo[_intervalos(periodos)].append(uf)
    partes = []
    for intervalo, ufs in por_intervalo.items():
        if ufs == [None]:
            quem = "Brasil"
        elif set(ufs) == set(sus.ALL_UFS):
            quem = "27 UFs"
        else:
            quem = ", ".join(sorted(ufs))
        partes.append(f"{quem}, {intervalo}")
    return "; ".join(sorted(partes))


def _harmonised(row: dict) -> str:
    """The categories the dictionary defines, then the scopes validated for them."""
    if not row["validated_scopes"]:
        return "—"
    analytics = sus.describe_dataset(row["name"])["analytics"]
    names = [label for key, label in CATEGORIES.items() if analytics.get(key)]
    named = names[0] if len(names) == 1 else f"{', '.join(names[:-1])} e {names[-1]}"
    return f"{named} em {_escopos(analytics['validated_sources'])}"


def _directory(path: str | None) -> str:
    return "—" if path is None else f"`{path.removeprefix(FTP_ROOT)}`"


def _profiles(system: str) -> str:
    """Links to the profiles in docs/sources/ whose title names a dataset of the system.

    ``# SIA · produção ambulatorial (`sia_*`)`` and
    ``# Medicamentos · ... (`sia_apac_medicamentos`)`` both go under SIA.
    """
    titles = {
        path.name: path.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ")
        for path in sorted((DOCS / "sources").glob("*.md"))
    }
    links = [
        f"[{title}](sources/{name})"
        for name, title in titles.items()
        if any(code.startswith(f"{system.lower()}_") for code in re.findall(r"`([^`]+)`", title))
    ]
    return ("Perfil: " if len(links) == 1 else "Perfis: ") + " · ".join(links)


def render() -> str:
    rows = sus.describe_datasets().to_dicts()
    lines = [HEADER.format(version=sus.__version__)]
    for system in dict.fromkeys(row["category"] for row in rows):
        lines += [f"## {system}", "", _profiles(system), "", TABLE]
        lines += [
            f"| `{row['name']}` | {row['title']} | {_publication(row)} | {_coverage(row)} | "
            f"{_labelled(row)} | {_harmonised(row)} |"
            for row in rows
            if row["category"] == system
        ]
        lines.append("")
    lines.append(SERVER.lstrip("\n"))
    lines += [
        f"| `{row['name']}` | `{row['prefix']}` | {_directory(row['ftp_dir'])} | "
        f"{_directory(row['prelim_dir'])} |"
        for row in rows
    ]
    return "\n".join(lines) + "\n" + OTHERS


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file differs from what the registry renders",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(
                f"{OUT} is stale. Run: uv run python scripts/gen_datasets_doc.py", file=sys.stderr
            )
            return 1
        return 0

    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
